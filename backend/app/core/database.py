"""Async SQLAlchemy engine, session factory, and the declarative Base.

One engine for the whole monolith. Domains import Base and the mixins from
here rather than creating their own connections.
"""

from collections.abc import AsyncGenerator
from datetime import datetime
from uuid import UUID, uuid4

from sqlalchemy import DateTime, func
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.config import settings

engine = create_async_engine(
    settings.database_url,
    echo=settings.db_echo,
    pool_pre_ping=True,
)

SessionLocal = async_sessionmaker(
    bind=engine,
    class_=AsyncSession,
    expire_on_commit=False,
)


class Base(DeclarativeBase):
    """Declarative base shared by every domain."""


class UUIDMixin:
    """UUID primary key.

    UUIDs rather than serial ints: ids end up in URLs and in logs, and a
    non-enumerable id is one less thing to think about with customer data.
    """

    # sort_order pins id to the front of every table and created_at to the
    # back, so columns read in a sensible order in psql instead of the
    # mixin's landing wherever the mapper happens to put them.
    id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, default=uuid4, sort_order=-100
    )


class CreatedAtMixin:
    """A server-set created_at.

    Deliberately no updated_at — nothing needs it yet. Adding one later is a
    single column here plus one autogenerated migration.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False, sort_order=100
    )


async def get_db() -> AsyncGenerator[AsyncSession, None]:
    """FastAPI dependency: one session per request."""
    async with SessionLocal() as session:
        try:
            yield session
            await session.commit()
        except Exception:
            await session.rollback()
            raise
