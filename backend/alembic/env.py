"""Alembic environment — async engine, URL and metadata pulled from the app."""

import asyncio
from logging.config import fileConfig

import sqlalchemy as sa
from alembic import context
from sqlalchemy.ext.asyncio import async_engine_from_config
from sqlalchemy import pool

from app.core.config import settings
from app.core.database import Base

# Importing this module registers every domain model on Base.metadata.
import app.models  # noqa: F401

config = context.config
config.set_main_option("sqlalchemy.url", settings.database_url)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def _enum_constraint_names() -> set[str]:
    """Constraint names generated by Enum(..., create_constraint=True).

    SQLAlchemy attaches a _create_rule to these, and Alembic's
    check-constraint comparison deliberately ignores metadata constraints that
    have one. The result is that it sees the constraint in the database, cannot
    find it in the models, and proposes dropping it — silently removing the
    validation on every status and channel column.

    Filtering them out by name leaves comparison working for any CHECK
    constraint we write by hand. Changing an enum's values still needs a
    hand-written migration that swaps the constraint; that was always true.
    """
    names = set()
    for table in target_metadata.tables.values():
        for column in table.columns:
            if isinstance(column.type, sa.Enum) and column.type.name:
                names.add(column.type.name)
    return names


ENUM_CONSTRAINT_NAMES = _enum_constraint_names()


def include_name(name, type_, parent_names) -> bool:
    if type_ == "check_constraint" and name in ENUM_CONSTRAINT_NAMES:
        return False
    return True


def run_migrations_offline() -> None:
    context.configure(
        url=settings.database_url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        include_name=include_name,
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,
        include_name=include_name,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
